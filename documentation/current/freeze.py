#!/usr/bin/env python3
"""Freeze official installed-release exports without replacing historical readers."""
import argparse
import hashlib
import html
import json
from pathlib import Path
import shutil

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def write(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def freeze(native, export, producer):
    identity = json.loads(producer.read_text())
    renderer = identity['renderer']
    assert renderer['selection'] == 'INSTALLED_RELEASE'
    assert identity['publicReleaseClaim'] is True
    target = HERE / 'site'
    assert not target.exists() and not (HERE / 'project').exists(), 'Preserve existing candidates before freezing'
    target.mkdir(parents=True)
    shutil.copytree(native, target / 'native')
    shutil.copytree(export, HERE / 'project', ignore=shutil.ignore_patterns('node_modules', 'build', '.docusaurus', 'clew-reader-packs', '.DS_Store'))
    projections = {}
    for manifest in [target / 'native/pages-manifest.json', HERE / 'project/export-manifest.json']:
        original_digest = digest(manifest)
        data = json.loads(manifest.read_text())
        data['output'] = '.'
        write(manifest, data)
        projections[str(manifest.relative_to(ROOT))] = {
            'originalSha256': original_digest, 'projection': 'Only output staging directory replaced with dot; exporter-owned file bytes are unchanged.'}
    identity['manifestProjections'] = projections
    write(target / 'producer.json', identity)
    version = html.escape(renderer['version'])
    revision = html.escape(renderer['sourceRevision'])
    (target / 'index.html').write_text('''<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Current Weather documentation</title><link rel="icon" href="data:image/svg+xml,%3Csvg%20xmlns=%22http://www.w3.org/2000/svg%22%20viewBox=%220%200%2032%2032%22%3E%3Ctext%20y=%2226%22%20font-size=%2228%22%3EW%3C/text%3E%3C/svg%3E"><style>body{font:16px/1.6 system-ui;color:#182033;max-width:65rem;margin:2rem auto;padding:0 1rem}a{color:#075fbd}li{margin:.6rem 0}code{overflow-wrap:anywhere}</style>
<nav><a href="../rendering/">Rendering showcase</a></nav><main><h1>Current Weather documentation</h1>
<p>Generated by official installed Codeclew ''' + version + '''. Read Markdown and complete domain field tables in either format.</p>
<ul><li><a href="native/overview.html">HTML documentation</a> · <a href="native/data-model/place.html#fields-and-representations">Place field table</a></li>
<li><a href="docusaurus/">Docusaurus documentation</a> · <a href="docusaurus/data-model/place#fields-and-representations">Place field table</a></li></ul>
<h2>Renderer and evidence</h2><p>Renderer revision <code>''' + revision + '''</code>. The original retained publication, descriptions and source evidence are preserved. Readable names are evidence-bound authored proposals. No recapture or runtime replay was performed.</p>
<p><a href="producer.json">Producer and input identities</a> · <a href="native/pages-manifest.json">HTML manifest</a> · <a href="../render-catalog/">Historical catalogue</a></p></main></html>''')
    policy = {**identity, 'schema': 'weather-current-publication/1.0', 'filesSha256': {}}
    paths = [target, HERE / 'project', ROOT / 'documentation/markdown-tables']
    for folder in paths:
        for path in sorted(folder.rglob('*')):
            if path.is_file() and '__pycache__' not in path.parts:
                policy['filesSha256'][str(path.relative_to(ROOT))] = digest(path)
    write(HERE / 'publication.json', policy)
    return policy


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--native', type=Path, required=True)
    parser.add_argument('--export', type=Path, required=True)
    parser.add_argument('--producer', type=Path, required=True)
    args = parser.parse_args()
    policy = freeze(args.native, args.export, args.producer)
    print(json.dumps({'renderer': policy['renderer'], 'frozenFiles': len(policy['filesSha256'])}, indent=2))
